-- Requires public.is_admin() and public.is_active_user(). Safe to re-run.
-- Keep memory_cards_private OUT of the Data API exposed schemas.
-- Existing images and ongoing game snapshots are preserved.
begin;
create schema if not exists memory_cards_private;
revoke all on schema memory_cards_private from public, anon;
grant usage on schema memory_cards_private to authenticated;

create table if not exists public.memory_cards (
  id bigint generated by default as identity primary key,
  image text not null,
  created_at timestamptz not null default now()
);
alter table public.memory_cards
  add column if not exists name text not null default '',
  add column if not exists category text not null default '',
  add column if not exists is_active boolean not null default true,
  add column if not exists deleted_at timestamptz,
  add column if not exists updated_at timestamptz not null default now(),
  add column if not exists version bigint not null default 1,
  add column if not exists storage_path text;
create index if not exists memory_cards_catalog_idx on public.memory_cards (created_at desc,id desc)
  where is_active and deleted_at is null;
create index if not exists memory_cards_trash_idx on public.memory_cards (deleted_at desc,id desc)
  where deleted_at is not null;

alter table public.memory_cards enable row level security;
-- This table belongs to the memory-card feature. Replace legacy permissive policies.
do $$ declare p record; begin
  for p in select policyname from pg_policies where schemaname='public' and tablename='memory_cards' loop
    execute format('drop policy %I on public.memory_cards',p.policyname);
  end loop;
end $$;
create policy memory_cards_read on public.memory_cards for select to authenticated
  using (public.is_active_user() and (public.is_admin() or (is_active and deleted_at is null)));
revoke all on public.memory_cards from anon;
revoke insert,update,delete on public.memory_cards from authenticated;
grant select on public.memory_cards to authenticated;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('memory-card-images','memory-card-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do nothing;
drop policy if exists memory_card_images_admin_select on storage.objects;
create policy memory_card_images_admin_select on storage.objects for select to authenticated
  using (bucket_id='memory-card-images' and public.is_active_user() and public.is_admin());
drop policy if exists memory_card_images_admin_insert on storage.objects;
create policy memory_card_images_admin_insert on storage.objects for insert to authenticated
  with check (bucket_id='memory-card-images' and public.is_active_user() and public.is_admin()
    and name ~ '^memory-cards/[0-9a-f-]{36}\.(webp|jpg|png)$');
-- Only unused uploads can be cleaned up. Referenced/trash images remain available
-- for restored cards and saved game snapshots. No overwrite policy is granted.
create or replace function memory_cards_private.can_remove_upload(p_path text)
returns boolean language sql stable security definer set search_path='' as $$
  select public.is_active_user() and public.is_admin()
    and not exists(select 1 from public.memory_cards where storage_path=p_path);
$$;
drop policy if exists memory_card_images_admin_cleanup on storage.objects;
create policy memory_card_images_admin_cleanup on storage.objects for delete to authenticated
  using (bucket_id='memory-card-images' and memory_cards_private.can_remove_upload(name));

create or replace function memory_cards_private.require_admin()
returns void language plpgsql security invoker set search_path='' as $$
begin
  if auth.uid() is null or not coalesce(public.is_active_user(),false) or not coalesce(public.is_admin(),false) then
    raise exception 'Chỉ quản trị viên đang hoạt động được quản lý ảnh.' using errcode='42501';
  end if;
end;
$$;

create or replace function memory_cards_private.catalog()
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare result jsonb;
begin
  if auth.uid() is null or not coalesce(public.is_active_user(),false) then
    raise exception 'Vui lòng đăng nhập bằng tài khoản đang hoạt động.' using errcode='42501';
  end if;
  select coalesce(jsonb_agg(to_jsonb(c) order by c.created_at desc,c.id desc),'[]'::jsonb) into result
  from (select * from (
    select distinct on (image) id,image,name,category,created_at from public.memory_cards
    where is_active and deleted_at is null order by image,created_at desc,id desc
  ) unique_images order by created_at desc,id desc limit 64) c;
  return result;
end;
$$;

create or replace function memory_cards_private.list_cards(
  p_search text,p_category text,p_view text,p_sort text,p_limit integer,p_offset integer
) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare result jsonb; v_search text:=nullif(lower(btrim(p_search)),'');
begin
  perform memory_cards_private.require_admin();
  if p_view is null or p_view not in ('all','active','paused','trash') or p_sort is null or p_sort not in ('newest','oldest','name') then
    raise exception 'Bộ lọc không hợp lệ.' using errcode='22023';
  end if;
  with catalog as (select (value->>'id')::bigint id from jsonb_array_elements(memory_cards_private.catalog())),
  filtered as (
    select c.*,exists(select 1 from catalog where catalog.id=c.id) as in_catalog from public.memory_cards c
    where (case when p_view='trash' then c.deleted_at is not null else c.deleted_at is null end)
      and (p_view not in ('active','paused') or c.is_active=(p_view='active'))
      and (nullif(p_category,'') is null or c.category=p_category)
      and (v_search is null or position(v_search in lower(concat_ws(' ',nullif(c.name,''),'Ảnh số '||c.id,c.category)))>0)
  ), page as (
    select * from filtered order by
      case when p_sort='name' then lower(name) end,
      case when p_sort='oldest' then created_at end asc,
      case when p_sort='newest' then created_at end desc,id desc
    limit least(greatest(coalesce(p_limit,24),1),100) offset greatest(coalesce(p_offset,0),0)
  )
  select jsonb_build_object('rows',(select coalesce(jsonb_agg(to_jsonb(p)),'[]'::jsonb) from page p),
    'total_count',(select count(*) from filtered),
    'summary',(select jsonb_build_object('total',count(*) filter(where deleted_at is null),
      'active',count(*) filter(where deleted_at is null and is_active),
      'paused',count(*) filter(where deleted_at is null and not is_active),
      'trash',count(*) filter(where deleted_at is not null),'catalog',(select count(*) from catalog)) from public.memory_cards),
    'categories',(select coalesce(jsonb_agg(category order by lower(category)),'[]'::jsonb)
      from (select distinct category from public.memory_cards where deleted_at is null and category<>'') categories)
  ) into result;
  return result;
end;
$$;

create or replace function memory_cards_private.save_card(p_id bigint,p_version bigint,p_document jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_card public.memory_cards; v_path text:=nullif(p_document->>'storage_path','');
begin
  perform memory_cards_private.require_admin();
  if p_document is null or jsonb_typeof(p_document) is distinct from 'object'
    or length(btrim(coalesce(p_document->>'name',''))) not between 1 and 120
    or length(btrim(coalesce(p_document->>'category','')))>60
    or jsonb_typeof(p_document->'is_active') is distinct from 'boolean' then
    raise exception 'Thông tin ảnh không hợp lệ.' using errcode='22023';
  end if;
  if p_id is null then
    if v_path is null or v_path !~ '^memory-cards/[0-9a-f-]{36}\.(webp|jpg|png)$'
      or not exists(select 1 from storage.objects where bucket_id='memory-card-images' and name=v_path)
      or coalesce(p_document->>'image','') !~ '^https://[^/[:space:]]+/storage/v1/object/public/memory-card-images/memory-cards/[0-9a-f-]{36}\.(webp|jpg|png)$'
      or right(p_document->>'image',length(v_path))<>v_path then
      raise exception 'Ảnh tải lên không hợp lệ.' using errcode='22023';
    end if;
    insert into public.memory_cards(image,name,category,is_active,storage_path)
      values(p_document->>'image',btrim(p_document->>'name'),btrim(coalesce(p_document->>'category','')),
        (p_document->>'is_active')::boolean,v_path) returning * into v_card;
  else
    select * into v_card from public.memory_cards where id=p_id for update;
    if not found then raise exception 'Không tìm thấy ảnh.' using errcode='P0002'; end if;
    if p_version is null or v_card.version<>p_version or v_card.deleted_at is not null then
      raise exception 'Ảnh đã thay đổi ở phiên khác. Hãy tải lại.' using errcode='40001';
    end if;
    update public.memory_cards set name=btrim(p_document->>'name'),category=btrim(coalesce(p_document->>'category','')),
      is_active=(p_document->>'is_active')::boolean,updated_at=clock_timestamp(),version=version+1
      where id=p_id returning * into v_card;
  end if;
  return to_jsonb(v_card);
end;
$$;

create or replace function memory_cards_private.change_card(p_id bigint,p_version bigint,p_action text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_card public.memory_cards;
begin
  perform memory_cards_private.require_admin();
  if p_action is null or p_action not in ('delete','restore') then raise exception 'Thao tác không hợp lệ.' using errcode='22023'; end if;
  select * into v_card from public.memory_cards where id=p_id for update;
  if not found then raise exception 'Không tìm thấy ảnh.' using errcode='P0002'; end if;
  if p_version is null or v_card.version<>p_version or (p_action='restore')=(v_card.deleted_at is null) then
    raise exception 'Ảnh đã thay đổi ở phiên khác. Hãy tải lại.' using errcode='40001';
  end if;
  update public.memory_cards set deleted_at=case when p_action='delete' then clock_timestamp() else null end,
    version=version+1,updated_at=clock_timestamp() where id=p_id returning * into v_card;
  return to_jsonb(v_card);
end;
$$;

create or replace function public.memory_cards_catalog()
returns jsonb language sql stable security invoker set search_path='' as $$select memory_cards_private.catalog()$$;
create or replace function public.admin_list_memory_cards(p_search text default null,p_category text default null,p_view text default 'all',
  p_sort text default 'newest',p_limit integer default 24,p_offset integer default 0)
returns jsonb language sql stable security invoker set search_path='' as $$
  select memory_cards_private.list_cards(p_search,p_category,p_view,p_sort,p_limit,p_offset);
$$;
create or replace function public.admin_save_memory_card(p_id bigint,p_version bigint,p_document jsonb)
returns jsonb language sql security invoker set search_path='' as $$select memory_cards_private.save_card(p_id,p_version,p_document)$$;
create or replace function public.admin_change_memory_card(p_id bigint,p_version bigint,p_action text)
returns jsonb language sql security invoker set search_path='' as $$select memory_cards_private.change_card(p_id,p_version,p_action)$$;
revoke all on all functions in schema memory_cards_private from public,anon,authenticated;
grant execute on function memory_cards_private.can_remove_upload(text),memory_cards_private.catalog(),
  memory_cards_private.list_cards(text,text,text,text,integer,integer),memory_cards_private.save_card(bigint,bigint,jsonb),
  memory_cards_private.change_card(bigint,bigint,text) to authenticated;
revoke all on function public.memory_cards_catalog(),public.admin_list_memory_cards(text,text,text,text,integer,integer),
  public.admin_save_memory_card(bigint,bigint,jsonb),public.admin_change_memory_card(bigint,bigint,text) from public,anon;
grant execute on function public.memory_cards_catalog(),public.admin_list_memory_cards(text,text,text,text,integer,integer),
  public.admin_save_memory_card(bigint,bigint,jsonb),public.admin_change_memory_card(bigint,bigint,text) to authenticated;
notify pgrst,'reload schema';
commit;
